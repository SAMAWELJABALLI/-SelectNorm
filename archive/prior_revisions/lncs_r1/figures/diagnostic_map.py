"""Data for the appendix figure 'Disagreement-advantage diagnostic map' (no new computation).

Copies, for each encoder-corpus pair, the archived AUC of the label-free, target-cross-fitted
disagreement estimator (auc_pi_tgt) and of the source-trained conditional-advantage estimator
(auc_rho_src), with their archived 95% bootstrap intervals, from paper/tables/mechanism_table.csv
(Arabic-script classifier, T_cons, mean of five seeds). Writes figures/diagnostic_map.csv.
"""
import ast, csv, os
HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', '..', 'paper', 'tables', 'mechanism_table.csv')
SETS = {'S3_tsac_lat': 'S3', 'S4_tunizi': 'S4', 'S5_narabizi': 'S5', 'S6_myc_lat': 'S6'}
rows = []
for r in csv.DictReader(open(SRC)):
    pl, ph = ast.literal_eval(r['auc_pi_tgt_ci'])
    rl, rh = ast.literal_eval(r['auc_rho_src_ci'])
    rows.append(dict(encoder=r['encoder'], set=SETS[r['set']], auc_pi=round(float(r['auc_pi_tgt']), 4),
                     auc_pi_lo=round(pl, 4), auc_pi_hi=round(ph, 4), auc_rho=round(float(r['auc_rho_src']), 4),
                     auc_rho_lo=round(rl, 4), auc_rho_hi=round(rh, 4)))
with open(os.path.join(HERE, 'diagnostic_map.csv'), 'w', newline='') as fh:
    w = csv.DictWriter(fh, fieldnames=list(rows[0]))
    w.writeheader(); w.writerows(rows)
print(len(rows), 'rows')

# pgfplots source (grayscale): marker shape = encoder, fill = corpus, bars = archived 95% intervals
MARK = {'mE5': 'o', 'XLM-R': 'square*', 'LaBSE': 'triangle*', 'MARBERTv2': 'diamond*'}
FILL = {'S3': 'white', 'S4': 'black!25', 'S5': 'black!60', 'S6': 'black'}
out = [r'% generated by diagnostic_map.py from diagnostic_map.csv; do not edit by hand',
       r'\begin{tikzpicture}',
       r'\begin{axis}[width=5.9cm, height=3.9cm, xmin=0.45, xmax=0.80, ymin=0.33, ymax=0.80,',
       r'  xlabel={AUC of $\hat\pi$ (disagreement)}, ylabel={AUC of $\hat\rho$ (advantage)},',
       r'  label style={font=\footnotesize}, tick label style={font=\footnotesize}, xtick={0.5,0.6,0.7,0.8}, ytick={0.4,0.5,0.6,0.7,0.8},',
       r'  axis lines*=left, clip=false, legend cell align=left, ',
       r'  error bars/error bar style={black!45, line width=0.4pt}]',
       r'\draw[black!55, dashed] (axis cs:0.5,0.33) -- (axis cs:0.5,0.80);',
       r'\draw[black!55, dashed] (axis cs:0.45,0.5) -- (axis cs:0.80,0.5);',
       r'\draw[black!35, dotted, thick] (axis cs:0.45,0.45) -- (axis cs:0.80,0.80);',
       r'\node[font=\scriptsize, text=black!60, anchor=south west] at (axis cs:0.50,0.745) {chance};',
       r'\node[font=\scriptsize, text=black!60, anchor=south west] at (axis cs:0.452,0.503) {chance};',
       r'\node[font=\scriptsize, text=black!60, rotate=40, anchor=south] at (axis cs:0.76,0.76) {$y=x$};']
for enc in MARK:
    for s in FILL:
        r = next(r for r in rows if r['encoder'] == enc and r['set'] == s)
        out.append(r'\addplot[only marks, mark=%s, mark size=%s, mark options={draw=black, fill=%s, line width=0.5pt}, forget plot,'
                   r' error bars/.cd, x dir=both, x explicit, y dir=both, y explicit] coordinates {(%.4f,%.4f) -= (%.4f,%.4f) += (%.4f,%.4f)};'
                   % ('*' if MARK[enc] == 'o' else MARK[enc], '2.2pt' if MARK[enc] != 'diamond*' else '2.6pt', FILL[s],
                      r['auc_pi'], r['auc_rho'], r['auc_pi'] - r['auc_pi_lo'], r['auc_rho'] - r['auc_rho_lo'],
                      r['auc_pi_hi'] - r['auc_pi'], r['auc_rho_hi'] - r['auc_rho']))
# legend entries (markers and fills)
for enc, m in MARK.items():
    out.append(r'\addlegendimage{only marks, mark=%s, mark size=2.2pt, mark options={draw=black, fill=white}}\label{dm:%s}' % ('*' if m == 'o' else m, enc.replace('-', '')))
for s, f in zip(FILL, ['$S_3$ TSAC', '$S_4$ TUNIZI', '$S_5$ NArabizi', '$S_6$ MYC']):
    out.append(r'\addlegendimage{only marks, mark=square*, mark size=2.2pt, mark options={draw=black, fill=%s}}\label{dm:%s}' % (FILL[s], s))
out += [r'\end{axis}', r'\end{tikzpicture}']
open(os.path.join(HERE, 'diagnostic_map.tex'), 'w').write('\n'.join(out) + '\n')
