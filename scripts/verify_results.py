"""Recompute the paper's archived numbers from the archived evidence and compare them with R3.

Needs only numpy and pandas (and the repository). No corpus text, feature file or encoder is used.
Checks, each with an explicit tolerance:

  C1  sha256 of every per-example export against results/export/per_example/manifest.json  (exact)
  C2  macro-F1 recomputed from the per-example exports (labels + routed predictions) against the
      run logs results/metrics/<backend>/runs_main.jsonl, lambda = 0, per seed             (|d| <= 1e-6)
  C3  seed-averaged macro-F1 from the run logs against every cell of paper/tables/main.tex
      (Table 2) and main_syn.tex: printed value must equal the value rounded to 1 decimal  (exact)
  C4  paired bootstrap re-run with scripts/reproduce_stats.py (10,000 resamples, seed 12345)
      against results/statistics/<backend>/main.json: diff, lo, hi, p, p_holm               (|d| <= 1e-9)
  C5  figure data: paper/figures/pareto.csv against the run logs (cost and macro-F1 means
      and seed SDs per system, set and lambda)                                              (|d| <= 1e-9)
  C7  few-label figure data: paper/figures/fewlabel.csv against runs_adapt.jsonl (mE5)        (|d| <= 1e-9)
  C8  normaliser accuracy table paper/tables/intrinsic.tex against results/metrics/intrinsic.json
      (printed value equals the value rounded as printed)                                   (exact)
  C9  cost-accounting fix (docs/DEVIATIONS.md D4): lambda = 0 rows of the pre-fix runs
      (results/archive/pre_cost_fix) have the same macro-F1 and selection rate as the current runs (|d| <= 1e-9)
  C6  tables regenerated by src.evaluation.tables from the archive against paper/tables/*.tex,
      after mapping the generator's US spellings to the paper's British ones                (exact)

Writes reproducibility/verification_results.json and exits non-zero if any check fails.
    python3 scripts/verify_results.py [--quick]   (--quick skips C4, which takes a few minutes)
"""
import argparse, glob, hashlib, json, os, re, subprocess, sys, tempfile
import numpy as np
import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EXP = os.path.join(ROOT, 'results', 'export', 'per_example')
SETS = ['S3_tsac_lat', 'S4_tunizi', 'S5_narabizi', 'S6_myc_lat']
ENCS = ['enc_intfloat__multilingual-e5-base', 'enc_FacebookAI__xlm-roberta-base',
        'enc_sentence-transformers__LaBSE', 'enc_UBC-NLP__MARBERTv2']
ROWS = [('B0_original', 'B0 original'), ('B1_always', 'B1 always normalise'), ('B2_random', 'B2 random, matched rate'),
        ('B3_conf', 'B3 confidence threshold'), ('B4_direct_gain', 'B4 direct gain'), ('B4b_abs_loss', 'B4b per-view loss'),
        ('B5_selectnorm_src', 'SelectNorm-src'), ('B5_selectnorm_adapt', 'SelectNorm-adapt'),
        ('B5_selectnorm_adapt_theory', 'Bayes threshold'), ('R_two_view_ensemble', 'R two-view ensemble'),
        ('B6_oracle', 'B6 oracle')]


def macro_f1(y, p):
    f = []
    for c in (0, 1):
        tp = np.sum((p == c) & (y == c)); fp = np.sum((p == c) & (y != c)); fn = np.sum((p != c) & (y == c))
        f.append(2 * tp / (2 * tp + fp + fn) if 2 * tp + fp + fn else 0.0)
    return 100 * (f[0] + f[1]) / 2


def runs(b, tag='main'):
    d = pd.read_json(os.path.join(ROOT, 'results', 'metrics', b, f'runs_{tag}.jsonl'), lines=True)
    return d[d.system != 'DIAG']


def c1():
    man = json.load(open(os.path.join(EXP, 'manifest.json')))['files']
    bad = [f for f, m in man.items() if hashlib.sha256(open(os.path.join(EXP, f), 'rb').read()).hexdigest() != m['sha256']]
    return dict(n=len(man), failures=bad)


def c2():
    n, bad = 0, []
    for b in ENCS + [e + '+syn' for e in ENCS]:
        d = runs(b)
        d = d[d.lam.isna() | (d.lam == 0)].set_index(['system', 'set', 'seed']).macro_f1
        for s in SETS:
            e = pd.read_csv(os.path.join(EXP, b, f'{s}.csv.gz'))
            y = e.label.values
            for c in e.columns:
                m = re.match(r'yhat__(.+)__s(\d+)$', c)
                if not m:
                    continue
                v = macro_f1(y, e[c].values)
                ref = d.get((m.group(1), s, int(m.group(2))))
                n += 1
                if ref is None or abs(v - ref) > 1e-6:
                    bad.append([b, s, c, v, None if ref is None else float(ref)])
    return dict(n=n, failures=bad)


def table_cells(path):
    """Rows of a stacked-panel table: {(panel, label): [cells]} with the markup stripped."""
    out, panel = {}, -1
    for line in open(path):
        if '\\multicolumn{4}' in line:
            panel += 1
            continue
        if '&' not in line or '$S_3$' in line:
            continue
        cells = [c.strip() for c in line.replace('\\rowcolor{black!6}', '').rstrip().rstrip('\\').split('&')]
        lab = re.sub(r'\\quad|\$.*?\$|\\', '', cells[0]).strip()
        out[(panel, lab)] = [re.sub(r'\\textbf\{([^}]*)\}', r'\1', re.sub(r'\$.*?\$', '', c)).strip() for c in cells[1:]]
    return out


def c3():
    n, bad = 0, []
    for fname, suffix in [('main.tex', ''), ('main_syn.tex', '+syn')]:
        path = os.path.join(ROOT, 'paper', 'tables', fname)
        if not os.path.exists(path):
            continue
        cells = table_cells(path)
        for pi in range(2):
            pair = ENCS[2 * pi:2 * pi + 2]
            g = {}
            for b in pair:
                d = runs(b + suffix)
                d = d[d.lam.isna() | (d.lam == 0)].copy()
                d['system'] = d.system.str.replace(r'#\d+$', '', regex=True)
                g[b] = d.groupby(['system', 'set']).macro_f1.mean()
            for k, lab in ROWS:
                key = next((kk for kk in cells if kk[0] == pi and kk[1].startswith(lab)), None)
                if key is None:
                    bad.append([fname, pi, lab, 'row missing'])
                    continue
                vals = [g[b].get((k, s), np.nan) for b in pair for s in SETS]
                for printed, v in zip(cells[key], vals):
                    n += 1
                    if printed != f'{v:.1f}':
                        bad.append([fname, pi, lab, printed, float(v)])
    return dict(n=n, failures=bad)


def c4():
    n, bad = 0, []
    for b in ENCS:
        out = subprocess.run([sys.executable, '-I', os.path.join(ROOT, 'scripts', 'reproduce_stats.py'), EXP, b],
                             capture_output=True, text=True, check=True).stdout
        new = {(r['set'], r['a'], r['b']): r for r in json.loads(out)}
        old = {(r['set'], r['a'], r['b']): r for r in json.load(open(os.path.join(ROOT, 'results', 'statistics', b, 'main.json')))}
        for k, r in old.items():
            for f in ('diff', 'lo', 'hi', 'p', 'p_holm'):
                n += 1
                if k not in new or abs(new[k][f] - r[f]) > 1e-9:
                    bad.append([b, *k, f, r[f], new.get(k, {}).get(f)])
    return dict(n=n, failures=bad)


def c5():
    p = pd.read_csv(os.path.join(ROOT, 'paper', 'figures', 'pareto.csv'))
    d = runs(ENCS[0])
    n, bad = 0, []
    for r in p.itertuples():
        sub = d[(d.system == r.system) & (d.set == r.set) & ((d.lam == r.lam) if not np.isnan(r.lam) else d.lam.isna() | (d.lam == 0))]
        for col, v in [('f1', sub.macro_f1.mean()), ('f1_sd', sub.macro_f1.std()), ('cost', sub.rel_cost.mean())]:
            n += 1
            if abs(getattr(r, col) - v) > 1e-9:
                bad.append([r.system, r.set, r.lam, col, getattr(r, col), float(v)])
    return dict(n=n, failures=bad)


def c6():
    tmp = tempfile.mkdtemp()
    proc = subprocess.run([sys.executable, '-m', 'src.evaluation.tables', '--backends', ','.join(ENCS), '--main', ENCS[0], '--out', tmp],
                          cwd=ROOT, capture_output=True, text=True)
    brit = [('normalize', 'normalise'), ('normalizer', 'normaliser')]
    bad, n = [], 0
    for f in sorted(glob.glob(os.path.join(tmp, '*.tex'))):
        ref = os.path.join(ROOT, 'paper', 'tables', os.path.basename(f))
        if not os.path.exists(ref):
            continue
        s = open(f).read()
        for a, b in brit:
            s = s.replace(a, b)
        n += 1
        if s != open(ref).read():
            bad.append(os.path.basename(f))
    for f in ['mechanism_table.csv']:
        n += 1
        if open(os.path.join(tmp, f)).read() != open(os.path.join(ROOT, 'paper', 'figures', f)).read():
            bad.append(f)
    note = 'consistency table (RQ4) needs data/prepared and is not regenerated here' if proc.returncode else ''
    return dict(n=n, failures=bad, note=note)


def c7():
    p = pd.read_csv(os.path.join(ROOT, 'paper', 'figures', 'fewlabel.csv'))
    d = runs(ENCS[0], 'adapt')
    g = d.groupby(['set', 'system', 'k']).macro_f1.agg(['mean', 'std'])
    n, bad = 0, []
    for r in p.itertuples():
        for col, v in [('f1', g.loc[(r.set, r.system, r.k), 'mean']), ('sd', g.loc[(r.set, r.system, r.k), 'std'])]:
            n += 1
            if abs(getattr(r, col) - v) > 1e-9:
                bad.append([r.set, r.system, r.k, col, getattr(r, col), float(v)])
    return dict(n=n, failures=bad)


def c8():
    m = json.load(open(os.path.join(ROOT, 'results', 'metrics', 'intrinsic.json')))
    rows = {}
    for line in open(os.path.join(ROOT, 'paper', 'tables', 'intrinsic.tex')):
        mm = re.match(r'\$T_\{\\rm (\w+)\}\$ & (.*)\\\\', line.strip())
        if mm:
            rows[mm.group(1)] = [c.strip() for c in mm.group(2).split('&')]
    n, bad = 0, []
    for mode, cells in rows.items():
        t, na, neg = m[mode]['tarc_heldout'], m[mode]['narabizi'], m[mode]['tarc_negation']
        pr = lambda e: ('--' if e['foreign_precision'] == 0 or e['foreign_recall'] < 0.005 else f"{100 * e['foreign_precision']:.0f}") + f"/{100 * e['foreign_recall']:.0f}"
        exp = [f"{100 * t['arabizi_word_acc']:.1f}", pr(t), f"{100 * neg['negation_preserved']:.1f}", f"{100 * na['arabizi_word_acc']:.1f}", pr(na)]
        for a, b in zip(cells, exp):
            n += 1
            if a != b:
                bad.append([mode, a, b])
    return dict(n=n, failures=bad)


def c9():
    n, bad, changed = 0, [], 0
    for f in sorted(glob.glob(os.path.join(ROOT, 'results', 'archive', 'pre_cost_fix', '*', 'runs_main.jsonl'))):
        b = os.path.basename(os.path.dirname(f))
        m = pd.read_json(f, lines=True).merge(runs(b), on=['seed', 'set', 'system', 'lam'], suffixes=('_o', '_n'))
        m = m[m.system != 'DIAG']
        z = m[m.lam.isna() | (m.lam == 0)]
        for c in ('macro_f1', 'sel_rate'):
            n += len(z)
            bad += [[b, r.set, r.system, r.seed, c] for r in z[(z[c + '_o'] - z[c + '_n']).abs() > 1e-9].itertuples()]
        p = m[m.lam > 0]
        changed += int(((p.macro_f1_o - p.macro_f1_n).abs() > 1e-9).sum())
    return dict(n=n, failures=bad, note=f'{changed} lambda>0 rows changed macro-F1 (expected after the fix)')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--quick', action='store_true')
    a = ap.parse_args()
    checks = {'C1_export_checksums': c1, 'C2_f1_exports_vs_logs': c2, 'C3_table2_vs_logs': c3,
              'C5_fig2_data_vs_logs': c5, 'C6_tables_regenerated': c6, 'C7_fewlabel_data_vs_logs': c7,
              'C8_intrinsic_table_vs_json': c8, 'C9_cost_fix_lambda0_invariance': c9}
    if not a.quick:
        checks['C4_paired_bootstrap_rerun'] = c4
    out = {}
    for k, f in checks.items():
        r = f()
        r['status'] = 'PASS' if not r['failures'] else 'FAIL'
        out[k] = r
        print(f"{k:28s} {r['status']}  ({r['n']} comparisons, {len(r['failures'])} failures) {r.get('note', '')}")
    json.dump(out, open(os.path.join(ROOT, 'reproducibility', 'verification_results.json'), 'w'), indent=1, default=float)
    sys.exit(any(r['failures'] for r in out.values()))


if __name__ == '__main__':
    main()
